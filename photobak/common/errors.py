# 异常体系
# ---------------------------------------------------------------------------
class PhotobakError(Exception):
    """本项目所有受控异常的基类。

    带 ``code`` 的异常会走 :func:`get` 取到标准提示；
    没登记的 code 会退化为通用提示，但仍保留原始信息便于排障。
    """

    #: 子类可覆盖，作为未显式传 code 时的默认错误码
    default_code = "E701"

    def __init__(
        self,
        code: str | None = None,
        detail: str = "",
        *,
        cause: BaseException | None = None,
    ) -> None:
        self.code = code or self.default_code
        self.detail = detail
        self.cause = cause
        info = get(self.code)
        self.info: ErrInfo | None = info
        title = info.title if info else "未知错误"
        super().__init__(f"[{self.code}] {title}" + (f" —— {detail}" if detail else ""))

    @property
    def strategy(self) -> Strategy:
        return self.info.strategy if self.info else Strategy.ABORT

    @property
    def title(self) -> str:
        return self.info.title if self.info else "未知错误"

    @property
    def hint(self) -> str:
        return self.info.hint if self.info else "请把 `.photobak/logs/` 下的日志反馈给开发者。"

    def user_message(self) -> str:
        """拼装给用户看的完整提示：标题 + 具体原因 + 解决办法。"""
        parts = [f"【{self.code}】{self.title}"]
        if self.detail:
            parts.append(f"原因：{self.detail}")
        parts.append(f"解决办法：{self.hint}")
        return "\n".join(parts)


class LinkError(PhotobakError):
    """连接类错误（E1xx）。"""

