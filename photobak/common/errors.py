"""错误码表与异常分类。

设计要点
--------
1. **错误码规则**：``E<域><序号>``，域取值：
   1=连接 2=传输 3=存储 4=文件 5=校验 6=环境 7=内部。
2. **每条错误都带"用户可见提示"**，且提示必须给出**具体的解决办法**，
   而不是只说"操作失败"（用户明确要求）。
3. **每条错误都带"处理策略"**（:class:`Strategy`），由编排器统一执行，
   避免每个调用点各写一套 if/else 导致行为不一致。

为什么把错误码集中在一张表里？
    因为本项目第一优先级是"数据安全 + 可解释"。集中登记可以让"哪类错误会
    导致文件被拦截、哪类可以自动重试"一目了然，评审时不用翻遍代码。
"""

from __future__ import annotations

import enum
from dataclasses import dataclass
from typing import Optional


class Strategy(enum.Enum):
    """错误的统一处理策略。"""

    RETRY = "retry"        # 可自动重试（指数退避）
    SKIP = "skip"          # 跳过当前文件，继续处理其他文件
    PAUSE = "pause"        # 暂停整个任务，等待用户介入
    ABORT = "abort"        # 终止本次任务（但程序不退出）
    FATAL = "fatal"        # 终止本次任务并退出程序
    WARN = "warn"          # 仅提示，不中断


@dataclass(frozen=True)
class ErrInfo:
    """一条错误码的完整定义。"""

    code: str
    title: str            # 简短标题，如"未检测到设备"
    hint: str             # 用户可见的解决办法（必须具体、可执行）
    strategy: Strategy    # 统一处理策略


_REGISTRY: dict[str, ErrInfo] = {}


def _reg(code: str, title: str, hint: str, strategy: Strategy) -> None:
    if code in _REGISTRY:  # 防御：错误码不允许重复登记
        raise ValueError(f"错误码重复登记：{code}")
    _REGISTRY[code] = ErrInfo(code, title, hint, strategy)


def get(code: str) -> Optional[ErrInfo]:
    """按错误码取定义；未登记返回 None（调用方应回退到通用提示）。"""
    return _REGISTRY.get(code)


def all_codes() -> dict[str, ErrInfo]:
    return dict(_REGISTRY)


